# 1. Descripción: Se dan instrucciones detalladas paso a paso para cambiar el estado del programa.
# Paradigma: Imperativo
# Justificación: Corresponde al paradigma imperativo porque se enfoca en el "cómo", dictando una secuencia explícita de comandos que el programa debe ejecutar.

# 2. Descripción: El problema se divide en entidades independientes que agrupan datos (atributos) y comportamientos (métodos).
# Paradigma: Orientado a Objetos
# Justificación: Pertenece a la orientación a objetos porque modela el problema utilizando "objetos" que interactúan entre sí.

# 3. Descripción: El programa se construye evaluando funciones matemáticas puras, evitando el uso de variables que cambien de estado (datos mutables).
# Paradigma: Funcional
# Justificación: Se asocia al paradigma funcional porque su principio central es evaluar funciones sin alterar el estado general ni crear efectos secundarios.

# 4. Descripción: Se declaran reglas lógicas y hechos conocidos, dejando que el sistema deduzca automáticamente la solución a las consultas.
# Paradigma: Lógico
# Justificación: Es un paradigma lógico ya que utiliza un motor de inferencia para deducir respuestas a partir de una base de conocimiento predefinida.
