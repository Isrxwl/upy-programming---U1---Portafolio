# PPP (Pseudocódigo)
# INPUT
# 1. Leer el primer número
# 2. Leer el segundo número
# PROCESS
# 3. Calcular la suma sumando el primer y el segundo número
# 4. Determinar si el primer número es mayor que el segundo (resultado booleano)
# OUTPUT
# 5. Mostrar el resultado de la suma
# 6. Mostrar el resultado booleano de la comparación

# PPP enfocado a Python (Código funcional)

# INPUT
num1 = float(input("Ingresa el primer numero: "))
num2 = float(input("Ingresa el segundo numero: "))

# PROCESS
suma = num1 + num2
es_mayor = num1 > num2

# OUTPUT
print("La suma de los numeros es:", suma)
print("¿El primer numero es mayor que el segundo?:", es_mayor)
