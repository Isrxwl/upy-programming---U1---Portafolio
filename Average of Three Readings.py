# PPP (Pseudocódigo)
# 1. Definir la primera lectura de temperatura como 30
# 2. Definir la segunda lectura de temperatura como 25
# 3. Definir la tercera lectura de temperatura como 28
# 4. Calcular la suma total de las tres temperaturas
# 5. Dividir la suma total entre 3 para calcular el promedio
# 6. Mostrar el resultado del promedio en pantalla

# PPP enfocado a Python (Código funcional)
temp1 = 30
temp2 = 25
temp3 = 28
total = temp1 + temp2 + temp3
promedio = total / 3
print(promedio)

# Justificación
# La solución es imperativa porque se centra en el "cómo", dando instrucciones secuenciales y paso a paso para llegar al resultado mediante el uso de variables.
